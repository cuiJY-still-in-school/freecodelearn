from typing import Dict, List, Optional
from dataclasses import dataclass


@dataclass
class TaskStep:
    """A single step in a task plan"""

    tool: str
    parameters: Dict[str, any]
    reasoning: str


class TaskPlanner:
    """Task planning and orchestration"""

    def __init__(self, llm_client):
        self.llm_client = llm_client
        self.available_tools = ["bash", "read", "write", "edit", "glob"]

    async def create_plan(
        self, task: str, context: Dict = None, similar_experiences: List[Dict] = None
    ) -> Dict:
        """
        Create a plan of tool calls for a given task

        Args:
            task: The user's task description
            context: Additional context about the task
            similar_experiences: Previously successful solutions

        Returns:
            Plan with steps and explanation
        """
        context = context or {}
        experiences_text = ""
        if similar_experiences:
            experiences_text = "\n\nSimilar previous solutions:\n"
            for exp in similar_experiences[:3]:
                experiences_text += f"- {exp.get('task_description', 'Unknown task')}: {exp.get('success', False)}\n"

        prompt = f"""
        Create a detailed plan to accomplish the following task.

        Task: {task}
        {experiences_text}

        Available tools: {", ".join(self.available_tools)}
        
        Context:
        - Working directory: {context.get("working_dir", ".")}
        - Time of day: {context.get("time_of_day", "unknown")}
        
        Plan format (JSON):
        {{
            "explanation": "Detailed explanation of the approach",
            "steps": [
                {{
                    "tool": "tool_name",
                    "parameters": {{
                        "param_name": "param_value"
                    }},
                    "reasoning": "Why this step is needed"
                }}
            ],
            "estimated_steps": 3,
            "needs_confirmation": true/false
        }}
        
        The plan should be:
        1. Logical and well-organized
        2. Use the most appropriate tools
        3. Handle errors gracefully
        4. Be efficient and direct
        
        Return only the JSON object.
        """

        response = await self.llm_client.generate(prompt)

        # Extract and parse JSON
        import json
        import re

        json_match = re.search(r"\{.*\}", response, re.DOTALL)
        if json_match:
            try:
                plan = json.loads(json_match.group())
                return self._validate_and_enrich_plan(plan, task)
            except json.JSONDecodeError:
                pass

        # Fallback plan
        return {
            "explanation": "Default fallback plan",
            "steps": [],
            "estimated_steps": 1,
            "needs_confirmation": True,
        }

    def _validate_and_enrich_plan(self, plan: Dict, original_task: str) -> Dict:
        """Validate and enrich the generated plan"""

        # Ensure required fields exist
        plan.setdefault("explanation", "Plan generated by AI")
        plan.setdefault("steps", [])
        plan.setdefault("estimated_steps", len(plan.get("steps", [])))
        plan.setdefault("needs_confirmation", True)

        # Enrich steps with reasoning if missing
        for step in plan.get("steps", []):
            if "reasoning" not in step or not step["reasoning"]:
                step["reasoning"] = (
                    f"Step {step.get('tool', 'unknown')} is needed to proceed"
                )

        return plan

    def validate_tool_calls(self, tool_calls: List[Dict]) -> List[Dict]:
        """Validate and clean up tool calls"""

        valid_calls = []

        for call in tool_calls:
            tool_name = call.get("tool", "").lower()

            # Check if tool exists
            if tool_name in self.available_tools:
                valid_calls.append(
                    {
                        "tool": tool_name,
                        "parameters": call.get("parameters", {}),
                        "reasoning": call.get("reasoning", ""),
                    }
                )

        return valid_calls
